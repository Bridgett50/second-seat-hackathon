import { test, expect } from "@playwright/test";

const SESSION = "/session";
const TRANSCRIPT = "When will you deliver the vendor report?\nPay $50 tomorrow";
const ZERO_FINDINGS = "The team will review the quarterly menu.";

async function goFromPasteToCompleted(page, text: string) {
  await page.goto(SESSION);
  await expect(page.locator("#offline-label")).toContainText("Offline demo");
  await page.locator("#transcript-input").fill(text);
  await page.locator("#btn-redact").click();
  await expect(page.locator("#session-state")).toContainText("Review required");
  await page.locator("#btn-approve").click();
  await expect(page.locator("#session-state")).toContainText("Approved");
  await page.locator("#btn-analyze").click();
  await expect(page.locator("#session-state")).toContainText("Completed");
}

test("paste -> copy: edit draft, approve exact text, copy to clipboard", async ({
  page,
  context,
}) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  const createdPromise = page.waitForResponse(
    (r) =>
      r.url().endsWith("/api/session") && r.request().method() === "POST",
  );
  await goFromPasteToCompleted(page, TRANSCRIPT);
  const sessionId = ((await (await createdPromise).json()) as {
    sessionId: string;
  }).sessionId;

  // Citations resolve to #segments items containing the approved text.
  await expect(page.locator("#offline-label")).toBeVisible();
  const approvedLines = (
    ((await page.locator("#payload-text").textContent()) ?? "")
      .split("\n")
      .map((l) => l.trim())
      .filter((l) => l.length > 0)
  );
  const segmentTexts = await page
    .locator("#segments li")
    .evaluateAll((els) => els.map((e) => e.textContent?.trim() ?? ""));
  expect(segmentTexts).toEqual(approvedLines);
  const hrefs = await page
    .locator("#results .result .citations a")
    .evaluateAll((els) => els.map((e) => e.getAttribute("href")));
  expect(hrefs.length).toBeGreaterThan(0);
  for (const href of hrefs) {
    expect(href).toMatch(/^#seg-\d+$/);
    const id = (href as string).slice(1);
    const seg = page.locator(`#segments li#${id}`);
    await expect(seg).toHaveCount(1);
    expect(approvedLines).toContain(((await seg.textContent()) ?? "").trim());
  }

  // Draft section is visible after analysis; copy starts disabled.
  await expect(page.locator("#draft")).toBeVisible();
  await expect(page.locator("#draft-origin")).toContainText(
    "Written by you — not generated by the analyzer. Second Seat never sends it.",
  );
  await expect(page.locator("#btn-copy")).toBeDisabled();

  // Edit draft to a unique string, approve the exact text, copy it.
  const draft = `my reply ${Date.now()} — confirming receipt`;
  await page.locator("#draft-text").fill(draft);
  await expect(page.locator("#draft-status")).toContainText(
    "Review — approve to copy.",
  );
  await page.locator("#btn-draft-approve").click();
  await expect(page.locator("#draft-status")).toContainText(
    "Approved — ready to copy.",
  );
  await expect(page.locator("#btn-copy")).toBeEnabled();
  // Textarea still holds the approved text.
  expect(await page.locator("#draft-text").inputValue()).toBe(draft);
  await page.locator("#btn-copy").click();
  await expect(page.locator("#draft-note")).toContainText(
    "Copied locally. Nothing was sent.",
  );
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(
    draft,
  );

  // Editing after approval disables copy until re-approved.
  await page.locator("#draft-text").fill(`${draft} v2`);
  await expect(page.locator("#draft-status")).toContainText(
    "Edited — approve again",
  );
  await expect(page.locator("#btn-copy")).toBeDisabled();
  await expect(page.locator("#draft-status")).toContainText(
    "Review — approve to copy.",
  );
  await page.locator("#btn-draft-approve").click();
  await expect(page.locator("#btn-copy")).toBeEnabled();

  // Reject disables copy until re-approved.
  await page.locator("#btn-draft-reject").click();
  await expect(page.locator("#btn-copy")).toBeDisabled();
  await page.locator("#btn-draft-approve").click();
  await expect(page.locator("#btn-copy")).toBeEnabled();
  await page.locator("#btn-copy").click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(
    `${draft} v2`,
  );

  // Changing the transcript clears findings and the draft.
  const [txResp] = await Promise.all([
    page.waitForResponse(
      (r) =>
        r.url().endsWith("/api/session/transcript") &&
        r.request().method() === "POST",
    ),
    page.locator("#transcript-input").fill("Something entirely different"),
  ]);
  expect((await txResp.json()).draft).toBeNull();
  await expect(page.locator("#draft")).toBeHidden();
  await expect(page.locator("#btn-copy")).toBeDisabled();
  await expect(page.locator("#results .result")).toHaveCount(0);
  const state = await page.request.get(
    `/api/session/state?sessionId=${encodeURIComponent(sessionId)}`,
  );
  expect((await state.json()).draft).toBeNull();

  expect(page.url()).not.toContain("/briefs/demo");
  await expect(page.locator("#offline-label")).toBeVisible();
});

test("zero-findings transcript still reaches an approvable, copyable draft", async ({
  page,
  context,
}) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await goFromPasteToCompleted(page, ZERO_FINDINGS);
  await expect(page.locator("#results")).toContainText(
    "No findings in the approved transcript.",
  );
  await expect(page.locator("#draft")).toBeVisible();
  const draft = `noted ${Date.now()}`;
  await page.locator("#draft-text").fill(draft);
  await expect(page.locator("#draft-status")).toContainText(
    "Review — approve to copy.",
  );
  await page.locator("#btn-draft-approve").click();
  await expect(page.locator("#btn-copy")).toBeEnabled();
  await page.locator("#btn-copy").click();
  await expect(page.locator("#draft-note")).toContainText(
    "Copied locally. Nothing was sent.",
  );
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(
    draft,
  );
  expect(page.url()).not.toContain("/briefs/demo");
});
