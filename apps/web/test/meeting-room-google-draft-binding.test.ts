import { test, expect } from "vitest";
import { randomUUID } from "node:crypto";
import { createMeetingRoomService } from "../src/meetingRoom.js";
test("approvedGoogleDraftAs binds exact body+identity lifecycle", async () => {
  const svc = createMeetingRoomService({ env: { SECOND_SEAT_TEST_MODE: "0" }, conversationInput: true, candidateAutoDispatch: false, sessionPolicy: true });
  const key = randomUUID();
  const headers = { host: "127.0.0.1:4174" };
  const opened = svc.open("", headers, key);
  const roomId = opened.roomId;
  expect(svc.approvedGoogleDraftAs(key, roomId)).toBeNull();
  expect(svc.approvedGoogleDraftAs(null, roomId)).toBeNull();
  expect(svc.approvedGoogleDraftAs(randomUUID(), roomId)).toBeNull();
  const edited = await svc.actAs(key, { roomId, action: "edit-draft", text: "We will confirm the date ourselves." }, headers);
  expect(edited.status).toBe(200);
  if (!edited.body.snapshot) throw new Error("missing snapshot after edit-draft");
  const pkg = edited.body.snapshot.packageId;
  if (!pkg) throw new Error("missing packageId");
  const approved = await svc.actAs(key, { roomId, action: "approve", packageId: pkg }, headers);
  expect(approved.status).toBe(200);
  if (!approved.body.snapshot) throw new Error("missing snapshot after approve");
  expect(approved.body.snapshot.view.draft.approved).toBe(true);
  const first = svc.approvedGoogleDraftAs(key, roomId);
  if (!first) throw new Error("missing approved binding");
  expect(Object.isFrozen(first)).toBe(true);
  expect(first.body).toBe(approved.body.snapshot.view.draft.body);
  expect(typeof first.identity).toBe("string");
  const firstIdentity = first.identity;
  await svc.actAs(key, { roomId, action: "edit-draft", text: "Other text." }, headers);
  expect(svc.approvedGoogleDraftAs(key, roomId)).toBeNull();
  const restored = await svc.actAs(key, { roomId, action: "edit-draft", text: "We will confirm the date ourselves." }, headers);
  if (!restored.body.snapshot) throw new Error("missing snapshot after restore");
  const pkg2 = restored.body.snapshot.packageId;
  if (!pkg2) throw new Error("missing packageId 2");
  const approved2 = await svc.actAs(key, { roomId, action: "approve", packageId: pkg2 }, headers);
  if (!approved2.body.snapshot) throw new Error("missing snapshot after second approve");
  expect(approved2.body.snapshot.view.draft.approved).toBe(true);
  const second = svc.approvedGoogleDraftAs(key, roomId);
  if (!second) throw new Error("missing second binding");
  expect(second.body).toBe(approved2.body.snapshot.view.draft.body);
  expect(second.identity).not.toBe(firstIdentity);
  await svc.actAs(key, { roomId, action: "takeover" }, headers);
  await svc.actAs(key, { roomId, action: "resume" }, headers);
  const afterResume = await svc.actAs(key, { roomId, action: "state" }, headers);
  if (!afterResume.body.snapshot) throw new Error("missing snapshot after resume");
  const pkg3 = afterResume.body.snapshot.packageId;
  if (!pkg3) throw new Error("missing packageId 3");
  const approved3 = await svc.actAs(key, { roomId, action: "approve", packageId: pkg3 }, headers);
  if (!approved3.body.snapshot) throw new Error("missing snapshot after third approve");
  const third = svc.approvedGoogleDraftAs(key, roomId);
  if (!third) throw new Error("missing third binding");
  expect(third.body).toBe(approved3.body.snapshot.view.draft.body);
  expect(third.identity).not.toBe(second.identity);
});
