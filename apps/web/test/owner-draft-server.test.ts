import { test, expect } from "vitest";
import { chromium, expect as browserExpect, type Browser } from "@playwright/test";
import { existsSync } from "node:fs";
import { startOwnerDraftFixture } from "./ownerDraftServerFixture.js";
import type { MeetingRoomSnapshot } from "../src/meetingRoom.js";
test("owner draft server",{timeout:40000},async()=>{
const h=await startOwnerDraftFixture();
let browser:Browser|undefined;
try{
const chromePath=process.env.PLAYWRIGHT_CHROME_PATH||(existsSync("C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe")?"C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe":existsSync("/usr/bin/google-chrome")?"/usr/bin/google-chrome":undefined);
browser=await chromium.launch({headless:true,...(chromePath?{executablePath:chromePath}:{channel:"chrome" as const})});
const page=await browser.newPage();
const urls:string[]=[];
page.on("request",r=>urls.push(r.url()));
await page.route("**/*",r=>new URL(r.request().url()).origin===h.origin?r.continue():r.abort());
const postClick=async(sel:string,path:string)=>{const p=page.waitForResponse(r=>new URL(r.url()).pathname===path&&r.request().method()==="POST");await page.click(sel);const res=await p;expect(res.status()).toBe(200);return res.json();};
await page.goto(h.origin+"/meeting-room");
await browserExpect(page.locator("body")).toHaveAttribute("data-meet-worker","1");
await browserExpect(page.locator("body")).toHaveAttribute("data-google-connect","1");
await browserExpect(page.locator("body")).toHaveAttribute("data-google-draft","1");
await browserExpect(page.locator("body")).toHaveAttribute("data-ai-drafting","0");
const cookies=await page.context().cookies(h.origin);
const mrCookie=cookies.find(c=>c.name==="mr_store");if(!mrCookie)throw new Error("mr_store missing");
const begin=h.connections.begin(mrCookie.value,"gmail-draft");
const state=new URL(begin.url).searchParams.get("state");if(!state)throw new Error("state missing");
expect(await h.connections.complete(mrCookie.value,state,"synthetic-code")).toBe(true);
await page.reload();
const roomId=await page.locator("#mr-root").getAttribute("data-room-id");if(!roomId)throw new Error("roomId missing");
const body="Owner reviewed clean café body.\nPlease confirm the schedule.";
await page.fill("#package-editor",body);
let pr=page.waitForResponse(r=>new URL(r.url()).pathname==="/api/meeting-room"&&r.request().method()==="POST"&&(r.request().postDataJSON() as {action:string})?.action==="edit-draft");
await page.click("#package-save");let jr=await pr;expect(jr.status()).toBe(200);
let j=await jr.json() as {snapshot:MeetingRoomSnapshot};expect(j.snapshot.view.draft.body).toBe(body);
pr=page.waitForResponse(r=>new URL(r.url()).pathname==="/api/meeting-room"&&r.request().method()==="POST"&&(r.request().postDataJSON() as {action:string})?.action==="approve");
await page.click("#approve");jr=await pr;expect(jr.status()).toBe(200);
j=await jr.json() as {snapshot:MeetingRoomSnapshot};expect(j.snapshot.view.draft.approved).toBe(true);
await browserExpect(page.locator("#mr-approval-state")).toContainText("Approved: yes");
const approved=j.snapshot.view.draft.body;
const approvedRec=h.runtime.meetingRoom.approvedGoogleDraftAs(mrCookie.value,roomId);if(!approvedRec)throw new Error("approved missing");
expect(approvedRec.body).toBe(approved);
for(const [sel,val] of [["#mr-gmail-to","owner@example.test"],["#mr-gmail-subject","Owner follow-up"]] as const){const inv=page.waitForResponse(r=>new URL(r.url()).pathname==="/api/google/draft/invalidate");await page.fill(sel,val);expect((await inv).status()).toBe(200);}
let pj=await postClick("#mr-gmail-preview","/api/google/draft/preview") as {status:string;package:{to:string;subject:string;body:string};packageHash:string;expiresAt:number};
expect(pj.package).toEqual({to:"owner@example.test",subject:"Owner follow-up",body:approved});expect(pj.status).toBe("preview");expect(pj.packageHash).toMatch(/^[a-f0-9]{64}$/);expect(pj.expiresAt).toBeGreaterThan(Date.now());
await browserExpect(page.locator("#mr-gmail-package")).toContainText(approved);
await browserExpect(page.locator("#mr-gmail-create")).toBeDisabled();
let aj=await postClick("#mr-gmail-approve","/api/google/draft/approve") as {status:string;packageHash:string};
expect(aj.status).toBe("approved");expect(aj.packageHash).toBe(pj.packageHash);expect(h.gmailCalls.length).toBe(0);
await browserExpect(page.locator("#mr-gmail-create")).toBeEnabled();
const cj=await postClick("#mr-gmail-create","/api/google/draft/create") as {status:string;draftId:string;messageId:string;packageHash:string;journalStatus:string};
expect(cj).toMatchObject({status:"created",draftId:"draft-server-1",messageId:"message-server-1",packageHash:pj.packageHash,journalStatus:"confirmed"});
await browserExpect(page.locator("#mr-gmail-status")).toContainText("Gmail draft created");
await browserExpect(page.locator("#mr-gmail-status")).not.toContainText("delivered");
await browserExpect(page.locator("#mr-gmail-receipt")).toContainText("draft-server-1");
await browserExpect(page.locator("#mr-gmail-receipt")).toContainText("message-server-1");
await browserExpect(page.locator("#mr-gmail-receipt")).toContainText(pj.packageHash);
await browserExpect(page.locator("#mr-gmail-receipt")).toContainText("confirmed");
expect(h.gmailCalls.length).toBe(1);
const call=h.gmailCalls[0];if(!call?.init)throw new Error("gmail call missing");
expect(call.url).toBe("https://gmail.googleapis.com/gmail/v1/users/me/drafts");expect((call.init as {method:string}).method).toBe("POST");
const raw=(JSON.parse(String(call.init.body)) as {message:{raw:string}}).message.raw;
const mime=Buffer.from(raw,"base64url").toString("utf8");const sep=mime.indexOf("\r\n\r\n");expect(sep).toBeGreaterThanOrEqual(0);
const heads=mime.slice(0,sep).split("\r\n");expect(heads).toContain("To: owner@example.test");expect(heads).toContain("Subject: =?UTF-8?B?"+Buffer.from("Owner follow-up").toString("base64")+"?=");
expect(Buffer.from(mime.slice(sep+4).replace(/\s/g,""),"base64").toString("utf8")).toBe(approved);
await postClick("#mr-gmail-preview","/api/google/draft/preview");await postClick("#mr-gmail-approve","/api/google/draft/approve");
await browserExpect(page.locator("#mr-gmail-create")).toBeEnabled();
const inv2=page.waitForResponse(r=>new URL(r.url()).pathname==="/api/google/draft/invalidate");await page.fill("#package-editor","Changed owner text");expect((await inv2).status()).toBe(200);
await browserExpect(page.locator("#mr-gmail-create")).toBeDisabled();
await browserExpect(page.locator("#mr-gmail-receipt")).toContainText(pj.packageHash);
expect(h.gmailCalls.length).toBe(1);
for(const u of urls)expect(new URL(u).origin).toBe(h.origin);
}finally{try{await browser?.close();}finally{await h.close();}}});
